def default_module_config(module: str) -> dict[str, Any]:
    if module == "command_runner":
        return {
            "max_results": 100,
            "default_timeout_s": 30.0,
            "max_timeout_s": 600.0,
            "max_output_chars": 200_000,
        }
    if module == "prefect_worker":
        return {"work_pool": "default", "worker_count": 1, "extra_args": []}
    if module == "redis_queue_worker":
        return {
            "queue_name": "",
            "prefect_deployment": "",
            "prefect_deployment_lsm": "",
            "prefect_deployment_oct": "",
            "allowed_window_minutes": 10.0,
            "backlog_queue_name": "",
        }
    if module == "redis_queue_burst_worker":
        return {
            "queue_name": "",
            "prefect_deployment": "",
            "prefect_deployment_lsm": "",
            "prefect_deployment_oct": "",
            "allowed_window_minutes": 10.0,
            "backlog_queue_name": "",
        }
    if module == "watcher":
        return {
            "watcher_kind": "lsm",
            "watch_path": "",
            "redis_queue_name": "",
            "poll_interval": 5,
            "stability_seconds": 15,
            "force_resend": False,
            "project_name": "",
            "slice_offset": 0,
            "mosaic_ranges": "1:999999",
            "project_base_path": "",
            "min_complex_file_size_bytes": 1,
            "prefer_spectral_for_complex_with_spectral": True,
        }
    if module == "primocache_monitor":
        return {"poll_interval_s": 15.0}
    return {}


def merged_config(module: str, info: ModuleInfo | None) -> dict[str, Any]:
    base = default_module_config(module)
    if info and info.config:
        merged = {**base, **info.config}
        if module == "prefect_worker" and "extra_args" in info.config:
            merged["extra_args"] = list(info.config.get("extra_args") or [])
        return merged
    return base


def module_overview_rows(
    known: Sequence[str],
    modules: list[ModuleInfo],
    modules_err: str | None,
) -> tuple[list[dict[str, str]], str | None]:
    if modules_err:
        return [], modules_err
    by_name = {m.name: m for m in modules}
    rows: list[dict[str, str]] = []
    for name in known:
        m = by_name.get(name)
        if m is None:
            rows.append(
                {
                    "Module": name,
                    "State": "not loaded",
                    "Error": "—",
                    "Started": "—",
                }
            )
        else:
            started = "—"
            if m.started_at_unix and m.started_at_unix > 0:
                started = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(m.started_at_unix))
            err = (m.error or "").strip() or "—"
            if len(err) > 120:
                err = err[:117] + "…"
            rows.append(
                {
                    "Module": m.name,
                    "State": m.state,
                    "Error": err,
                    "Started": started,
                }
            )
    known_set = set(known)
    for m in modules:
        if m.name not in known_set:
            started = "—"
            if m.started_at_unix and m.started_at_unix > 0:
                started = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(m.started_at_unix))
            err = (m.error or "").strip() or "—"
            if len(err) > 120:
                err = err[:117] + "…"
            rows.append(
                {
                    "Module": m.name,
                    "State": m.state,
                    "Error": err,
                    "Started": started,
                }
            )
    return rows, None


def module_can_stop(info: ModuleInfo | None) -> bool:
    """True if the node has a module instance that is not already stopped."""
    if info is None:
        return False
    return info.state != "stopped"


def render_overview_stop_buttons(
    host: str,
    port: int,
    modules: list[ModuleInfo],
    known: Sequence[str],
    key: Callable[[str], str],
) -> None:
    """One row per known module with a Stop button (Overview tab)."""
    st.markdown("**Stop module**")
    st.caption("Stops a loaded module unless it is already **stopped** (works from error/starting too).")
    by_name = {m.name: m for m in modules}
    for name in known:
        m = by_name.get(name)
        col_a, col_b = st.columns([4, 1])
        with col_a:
            if m is None:
                st.markdown(f"`{name}` — not loaded")
            else:
                st.markdown(f"`{name}` — **{m.state}**")
        with col_b:
            if st.button(
                "Stop",
                key=key(f"ov_stop_{name}"),
                disabled=not module_can_stop(m),
            ):
                ok, msg = stop_module(host, port, module=name)
                if ok:
                    st.success(msg or "stopped")
                    st.rerun()
                else:
                    st.error(msg)


def _render_command_runner_result(result: dict[str, Any]) -> None:
    status = result.get("status", "unknown")
    job_id = result.get("job_id", "")
    command = result.get("command", "")
    exit_code = result.get("exit_code", 0)
    label = f"{status} — `{command[:40]}{'…' if len(command) > 40 else ''}`"
    if status in {"finished", "failed", "timed_out"}:
        label += f" [exit {exit_code}]"
    with st.expander(label, expanded=status in {"running", "queued"}):
        if job_id:
            st.caption(f"Job id: `{job_id}`")
        st.json(
            {
                "status": status,
                "command": command,
                "args": result.get("args", []),
                "shell": result.get("shell", False),
                "timeout_s": result.get("timeout_s", 0),
                "submitted_at_unix": result.get("submitted_at_unix", 0),
                "started_at_unix": result.get("started_at_unix", 0),
                "finished_at_unix": result.get("finished_at_unix", 0),
                "exit_code": exit_code,
                "timed_out": result.get("timed_out", False),
                "error": result.get("error", ""),
            }
        )
        stdout = result.get("stdout") or ""
        stderr = result.get("stderr") or ""
        if stdout:
            st.markdown("**stdout**")
            st.code(stdout, language="text")
        if stderr:
            st.markdown("**stderr**")
            st.code(stderr, language="text")


def _parse_args(text: str) -> list[str]:
    return [ln.strip() for ln in text.splitlines() if ln.strip()]


def render_module_tab(
    module: str,
    *,
    host: str,
    port: int,
    info: ModuleInfo | None,
    key: Callable[[str], str],
) -> None:
    cfg = merged_config(module, info)
    state = info.state if info else "not loaded"
    running = info is not None and state == "running"
    can_stop = module_can_stop(info)

    st.subheader(module.replace("_", " "))
    st.caption(f"State: **{state}**")
    if info and info.error:
        st.warning(info.error)

    if module == "command_runner":
        _tab_command_runner(host, port, info, cfg, running, can_stop, key)
    elif module == "prefect_worker":
        _tab_prefect_worker(host, port, info, cfg, running, can_stop, key)
    elif module == "redis_queue_worker":
        _tab_redis_queue_worker(host, port, info, cfg, running, can_stop, key)
    elif module == "redis_queue_burst_worker":
        _tab_redis_queue_burst_worker(host, port, info, cfg, running, can_stop, key)
    elif module == "watcher":
        _tab_watcher(host, port, info, cfg, running, can_stop, key)
    elif module == "primocache_monitor":
        _tab_primocache_monitor(host, port, info, cfg, running, can_stop, key)


def _tab_command_runner(
    host: str,
    port: int,
    info: ModuleInfo | None,
    cfg: dict[str, Any],
    running: bool,
    can_stop: bool,
    key: Callable[[str], str],
) -> None:
    st.caption("Queued command jobs and limits; use **Submit** below when running.")

    max_results = st.number_input(
        "Max stored results",
        min_value=1,
        max_value=10_000,
        value=int(cfg.get("max_results", 100)),
        step=10,
        key=key("m_cr_max_results"),
    )
    default_timeout = st.number_input(
        "Default timeout (seconds)",
        min_value=0.1,
        max_value=600.0,
        value=float(cfg.get("default_timeout_s", 30.0)),
        step=1.0,
        key=key("m_cr_default_timeout"),
    )
    max_timeout = st.number_input(
        "Max timeout (seconds)",
        min_value=0.1,
        max_value=3_600.0,
        value=float(cfg.get("max_timeout_s", 600.0)),
        step=10.0,
        key=key("m_cr_max_timeout"),
    )
    max_output = st.number_input(
        "Max output chars per stream",
        min_value=1_000,
        max_value=5_000_000,
        value=int(cfg.get("max_output_chars", 200_000)),
        step=10_000,
        key=key("m_cr_max_output"),
    )

    payload = {
        "max_results": int(max_results),
        "default_timeout_s": float(default_timeout),
        "max_timeout_s": float(max_timeout),
        "max_output_chars": int(max_output),
    }

    c1, c2 = st.columns(2)
    with c1:
        if st.button("Start", type="primary", disabled=running, key=key("m_cr_start")):
            ok, msg = start_module(host, port, module="command_runner", config=payload)
            if ok:
                st.success(msg or "started")
                st.rerun()
            else:
                st.error(msg)
    with c2:
        if st.button("Stop", disabled=not can_stop, key=key("m_cr_stop")):
            ok, msg = stop_module(host, port, module="command_runner")
            if ok:
                st.success(msg or "stopped")
                st.rerun()
            else:
                st.error(msg)

    if st.button("Apply config (restart module)", disabled=not running, key=key("m_cr_apply")):
        ok, msg = configure_module(host, port, module="command_runner", config=payload)
        if ok:
            st.success(msg or "reconfigured")
            st.rerun()
        else:
            st.error(msg)

    st.divider()
    st.markdown("**Jobs**")
    cr_command = st.text_input(
        "Runner command",
        value="",
        placeholder="e.g. echo or /usr/bin/uptime",
        key=key("m_cr_job_cmd"),
    )
    cr_args_text = st.text_area(
        "Runner args (one per line)",
        value="",
        height=100,
        placeholder="hello\nworld",
        key=key("m_cr_job_args"),
    )
    cr_shell = st.checkbox("Runner shell mode", value=False, key=key("m_cr_job_shell"))
    cr_timeout_s = st.number_input(
        "Runner timeout (seconds)",
        min_value=0.1,
        max_value=3_600.0,
        value=30.0,
        step=1.0,
        key=key("m_cr_job_timeout"),
    )
    if st.button(
        "Submit command job",
        type="primary",
        disabled=not running,
        key=key("m_cr_submit_job"),
    ):
        cmd = cr_command.strip()
        if not cmd:
            st.error("Command must be non-empty.")
        else:
            job_id, err = submit_command(
                host,
                port,
                command=cmd,
                args=_parse_args(cr_args_text),
                shell=cr_shell,
                timeout_s=float(cr_timeout_s),
            )
            if err:
                st.error(err)
            else:
                st.success(f"Submitted job `{job_id}`")

    lookup_job_id = st.text_input(
        "Lookup job id",
        value="",
        key=key("m_cr_lookup_job"),
    )
    if st.button("Get job", key=key("m_cr_get_job")):
        job_id = lookup_job_id.strip()
        if not job_id:
            st.error("Job id must be non-empty.")
        else:
            result, err = get_command_result(host, port, job_id=job_id)
            if err:
                st.error(err)
            elif result is not None:
                _render_command_runner_result(result)

    result_limit = st.number_input(
        "Stored result limit",
        min_value=1,
        max_value=1_000,
        value=20,
        step=1,
        key=key("m_cr_list_limit"),
    )
    if st.button("Refresh results list", disabled=not running, key=key("m_cr_refresh_results")):
        results, err = list_command_results(host, port, limit=int(result_limit))
        if err:
            st.error(err)
        elif not results:
            st.info("No command runner results stored.")
        else:
            for result in results:
                _render_command_runner_result(result)


